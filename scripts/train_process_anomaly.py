#!/usr/bin/env python3
"""
Train the process anomaly Isolation Forest and export to ONNX.

Approach
────────
1. (Optional) Load real process observations from SQLite `process_observations`
   table (--db path). These provide machine-specific normal baselines.
2. Generate synthetic normal and anomalous process samples to augment sparse
   real data or bootstrap the model from scratch.
3. Use IsolationForest to score all normal data; add synthetic anomalies.
4. Train a CalibratedClassifierCV(GradientBoostingClassifier) on the labeled
   dataset to produce well-calibrated probability output [normal_prob, anomaly_prob].
5. Export to ONNX (opset 17) with `predict_proba` as the output tensor "output".
6. Update models/manifest.json with the new SHA-256.

Feature vector layout (matches inference::detect_process_anomaly)
────────────────────────────────────────────────────────────────
  [cpu_pct, mem_mb, io_bytes_per_sec, process_age_hours, cpu_trend_5m]
  Index 0   Index 1  Index 2          Index 3            Index 4

On-device weekly retraining
────────────────────────────
When --db is provided and the table has ≥100 rows, real observations replace
the synthetic normal distribution. Anomaly labels are generated by IsolationForest
(contamination=0.05) on the real data. This requires only the SQLite file —
no internet connection, no labeled data.

Usage
─────
  # Bootstrap (synthetic only)
  python scripts/train_process_anomaly.py \
      --output models/process_anomaly_v1.onnx

  # On-device retrain from SQLite
  python scripts/train_process_anomaly.py \
      --db /var/lib/firstaid/agent.db \
      --output models/process_anomaly_v1.onnx \
      --manifest models/manifest.json

Dependencies
────────────
  pip install scikit-learn onnx skl2onnx numpy
"""

import argparse
import hashlib
import json
import random
import sqlite3
import sys
from pathlib import Path

import numpy as np

FEATURE_NAMES = [
    "cpu_pct",
    "mem_mb",
    "io_bytes_per_sec",
    "process_age_hours",
    "cpu_trend_5m",
]
N_FEATURES = len(FEATURE_NAMES)
MODEL_NAME = "process_anomaly_v1"

# ── Synthetic data generation ─────────────────────────────────────────────────

# Normal process profiles: (cpu_mean, cpu_std, mem_mean_mb, mem_std_mb)
NORMAL_PROFILES = [
    (2.0,  3.0,   50,   30),    # idle background daemon
    (8.0,  6.0,  200,  100),    # active user app (light)
    (20.0, 10.0, 800,  300),    # active user app (heavy)
    (35.0, 12.0, 2000, 500),    # compilation / indexing
    (50.0, 15.0, 400,  200),    # video playback
]


def generate_normal(n: int, rng: np.random.Generator) -> np.ndarray:
    samples = []
    for _ in range(n):
        profile = random.choice(NORMAL_PROFILES)
        cpu_mean, cpu_std, mem_mean, mem_std = profile
        cpu     = float(np.clip(rng.normal(cpu_mean, cpu_std), 0, 100))
        mem     = float(max(1, rng.normal(mem_mean, mem_std)))
        io      = float(max(0, rng.exponential(500_000)))   # bytes/s
        age     = float(max(0, rng.exponential(4)))          # hours
        trend   = float(rng.normal(0, 3))                   # %/5m change
        samples.append([cpu, mem, io, age, trend])
    return np.array(samples, dtype=np.float32)


def generate_anomalies(n: int, rng: np.random.Generator) -> np.ndarray:
    """Anomalies: runaway CPU, memory leak, sustained high io, or unusual trend."""
    samples = []
    for _ in range(n):
        kind = rng.integers(0, 4)
        if kind == 0:   # runaway CPU
            cpu   = float(rng.uniform(85, 100))
            mem   = float(rng.uniform(50, 500))
            io    = float(rng.exponential(200_000))
            age   = float(rng.exponential(0.5))
            trend = float(rng.uniform(5, 30))
        elif kind == 1:  # memory leak
            cpu   = float(rng.uniform(5, 40))
            mem   = float(rng.uniform(6000, 16000))
            io    = float(rng.exponential(100_000))
            age   = float(rng.uniform(20, 72))
            trend = float(rng.normal(0, 2))
        elif kind == 2:  # I/O storm
            cpu   = float(rng.uniform(30, 70))
            mem   = float(rng.uniform(100, 2000))
            io    = float(rng.uniform(500_000_000, 2_000_000_000))
            age   = float(rng.exponential(1))
            trend = float(rng.normal(0, 5))
        else:           # zombie process (high age, low resource)
            cpu   = float(rng.uniform(0, 2))
            mem   = float(rng.uniform(1, 10))
            io    = 0.0
            age   = float(rng.uniform(200, 500))
            trend = 0.0
        samples.append([cpu, mem, io, age, trend])
    return np.array(samples, dtype=np.float32)


# ── Real data loading ─────────────────────────────────────────────────────────

def load_real_observations(db_path: Path) -> np.ndarray | None:
    if not db_path.exists():
        print(f"WARNING: DB not found at {db_path}, using synthetic data only")
        return None
    try:
        con = sqlite3.connect(str(db_path))
        rows = con.execute(
            """SELECT cpu_pct, mem_mb, io_bytes_per_sec, process_age_hours, cpu_trend_5m
               FROM process_observations
               WHERE collected_at >= datetime('now', '-7 days')
               ORDER BY collected_at DESC"""
        ).fetchall()
        con.close()
    except Exception as e:
        print(f"WARNING: Could not read DB ({e}), using synthetic data only")
        return None

    if not rows:
        return None

    arr = np.array(rows, dtype=np.float32)
    print(f"Loaded {len(arr)} real process observations from {db_path}")
    return arr


# ── IsolationForest pseudo-labeling ──────────────────────────────────────────

def pseudo_label_with_isolation_forest(X_normal: np.ndarray,
                                        contamination: float = 0.05):
    """
    Run IsolationForest on X_normal to detect outliers within the normal data.
    Returns labels: 0=normal, 1=anomaly.
    Contamination = assumed fraction of anomalies already mixed in real data.
    """
    from sklearn.ensemble import IsolationForest
    iso = IsolationForest(n_estimators=100, contamination=contamination,
                           random_state=42)
    iso.fit(X_normal)
    # predict: 1=inlier, -1=outlier
    preds = iso.predict(X_normal)
    labels = np.where(preds == 1, 0, 1)   # 0=normal, 1=anomaly
    n_outliers = labels.sum()
    print(f"IsolationForest pseudo-labeling: {n_outliers}/{len(labels)} "
          f"samples flagged as anomalous ({contamination*100:.0f}% contamination)")
    return labels


# ── Model training ────────────────────────────────────────────────────────────

def train_model(X: np.ndarray, y: np.ndarray):
    """
    Train a CalibratedClassifierCV(GradientBoostingClassifier) for well-calibrated
    probability output. This exports cleanly to ONNX via skl2onnx.
    """
    from sklearn.calibration import CalibratedClassifierCV
    from sklearn.ensemble import GradientBoostingClassifier
    from sklearn.model_selection import StratifiedKFold
    from sklearn.preprocessing import StandardScaler
    from sklearn.pipeline import Pipeline

    pipe = Pipeline([
        ("scaler", StandardScaler()),
        ("clf", CalibratedClassifierCV(
            GradientBoostingClassifier(
                n_estimators=50,
                max_depth=4,
                learning_rate=0.1,
                subsample=0.8,
                random_state=42,
            ),
            cv=StratifiedKFold(n_splits=3),
            method="isotonic",
        )),
    ])

    pipe.fit(X, y)

    # Evaluate calibration quality on training data (quick sanity check)
    probs = pipe.predict_proba(X)
    pred_y = np.argmax(probs, axis=1)
    acc = (pred_y == y).mean()
    anom_recall = (pred_y[y == 1] == 1).mean() if (y == 1).any() else 0.0
    print(f"Training accuracy: {acc*100:.1f}%  |  Anomaly recall: {anom_recall*100:.1f}%")
    return pipe


# ── ONNX export ───────────────────────────────────────────────────────────────

def export_onnx(pipeline, output_path: Path):
    from skl2onnx import convert_sklearn
    from skl2onnx.common.data_types import FloatTensorType

    initial_type = [("input", FloatTensorType([None, N_FEATURES]))]
    options = {id(pipeline.named_steps["clf"]): {"nocl": False}}

    onnx_model = convert_sklearn(
        pipeline,
        initial_types=initial_type,
        options=options,
        target_opset=17,
    )

    # Rename the probability output to "output" so the Rust code can use a
    # single consistent key regardless of model type.
    for node in onnx_model.graph.output:
        if "probabilities" in node.name.lower() or node.name == "output_probability":
            node.name = "output"

    with open(output_path, "wb") as f:
        f.write(onnx_model.SerializeToString())

    size_kb = output_path.stat().st_size // 1024
    print(f"Exported ONNX model → {output_path}  ({size_kb} KB)")


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def update_manifest(model_path: Path, digest: str, manifest_path: Path,
                    obs_count: int):
    if not manifest_path.exists():
        print(f"WARNING: manifest not found at {manifest_path}, skipping update")
        return
    with open(manifest_path) as f:
        manifest = json.load(f)
    for m in manifest.get("models", []):
        if m.get("name") == MODEL_NAME:
            m["sha256"] = digest
            m["path"]   = str(model_path)
    with open(manifest_path, "w") as f:
        json.dump(manifest, f, indent=2)
    print(f"Updated manifest SHA-256 → {digest[:16]}…  (trained on {obs_count} obs)")


# ── CLI ───────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(
        description="Train process anomaly Isolation Forest → ONNX")
    parser.add_argument("--db",         default=None,
                        help="SQLite DB path for real process observations")
    parser.add_argument("--output",     default="models/process_anomaly_v1.onnx")
    parser.add_argument("--manifest",   default="models/manifest.json")
    parser.add_argument("--n-normal",   type=int, default=2000,
                        help="Synthetic normal samples (used when DB unavailable)")
    parser.add_argument("--n-anomaly",  type=int, default=400,
                        help="Synthetic anomaly samples appended to real data")
    parser.add_argument("--contamination", type=float, default=0.05,
                        help="IsolationForest contamination for pseudo-labeling real data")
    parser.add_argument("--seed",       type=int, default=42)
    args = parser.parse_args()

    rng = np.random.default_rng(args.seed)
    random.seed(args.seed)

    try:
        import sklearn   # noqa: F401
        from skl2onnx import convert_sklearn   # noqa: F401
    except ImportError:
        print("ERROR: pip install scikit-learn skl2onnx onnx numpy", file=sys.stderr)
        sys.exit(1)

    # ── Assemble training corpus ──────────────────────────────────────────────
    real_obs = None
    if args.db:
        real_obs = load_real_observations(Path(args.db))

    if real_obs is not None and len(real_obs) >= 100:
        print(f"Using {len(real_obs)} real observations as normal baseline")
        y_real   = pseudo_label_with_isolation_forest(real_obs, args.contamination)
        X_normal = real_obs[y_real == 0]
        X_real_anom = real_obs[y_real == 1]
    else:
        print(f"Generating {args.n_normal} synthetic normal samples…")
        X_normal = generate_normal(args.n_normal, rng)
        X_real_anom = np.zeros((0, N_FEATURES), dtype=np.float32)

    print(f"Generating {args.n_anomaly} synthetic anomaly samples…")
    X_synth_anom = generate_anomalies(args.n_anomaly, rng)

    X_anom = np.vstack([X_real_anom, X_synth_anom]) \
        if len(X_real_anom) > 0 else X_synth_anom

    X = np.vstack([X_normal, X_anom]).astype(np.float32)
    y = np.concatenate([
        np.zeros(len(X_normal), dtype=np.int64),
        np.ones(len(X_anom),   dtype=np.int64),
    ])

    obs_count = len(X)
    print(f"Total training samples: {obs_count}  "
          f"(normal={len(X_normal)}, anomaly={len(X_anom)})")

    # ── Train ──────────────────────────────────────────────────────────────────
    print("Training CalibratedClassifierCV(GradientBoostingClassifier)…")
    model = train_model(X, y)

    # ── Export ─────────────────────────────────────────────────────────────────
    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    print("Exporting to ONNX…")
    export_onnx(model, output_path)

    digest = sha256_of(output_path)
    print(f"SHA-256: {digest}")
    update_manifest(output_path, digest, Path(args.manifest), obs_count)

    print("\nDone. Verify inference with:")
    print("  cargo test -p inference --features onnx -- isolation_forest")


if __name__ == "__main__":
    main()
